import { defineOrvalConfig, type OrvalApiDescriptor } from './defineOrvalConfig';

const PATHS = {
  swaggerDir: './src/server/swagger',
  outDir: './src/server/autoGeneratedHooks',
  mutatorPath: './src/server/mutators',
};

const LINKS_API: OrvalApiDescriptor = {
  key: 'squezelinkApi',
  slug: 'squezelink',
  mutatorFile: 'squezelinkMutator',
  mutatorName: 'squezelinkInstance',
  label: 'Squezelink',
};

describe('defineOrvalConfig apis option', () => {
  it('with apis given, builds only those apis', () => {
    const options = { ...PATHS, apis: [LINKS_API] };

    const config = defineOrvalConfig(options);

    expect(Object.keys(config)).toEqual(['squezelinkApi']);
  });

  it('with apis given, wires input, output and mutator from the descriptor', () => {
    const options = { ...PATHS, apis: [LINKS_API] };

    const config = defineOrvalConfig(options);

    expect(config.squezelinkApi?.input.target).toBe('./src/server/swagger/squezelink.json');
    expect(config.squezelinkApi?.output.target).toBe('./src/server/autoGeneratedHooks/squezelink/index.ts');
    expect(config.squezelinkApi?.output.override).toEqual({
      mutator: { path: './src/server/mutators/squezelinkMutator.ts', name: 'squezelinkInstance' },
    });
  });

  it('with an empty apis list, builds no entries', () => {
    const options = { ...PATHS, apis: [] };

    const config = defineOrvalConfig(options);

    expect(config).toEqual({});
  });

  it('with infinite on the api and no operations, sets the infinite query on the whole api', () => {
    const options = { ...PATHS, apis: [{ ...LINKS_API, infinite: { cursorParam: 'cursor' } }] };

    const config = defineOrvalConfig(options);

    expect(config.squezelinkApi?.output.override.query).toEqual({
      useInfinite: true,
      useInfiniteQueryParam: 'cursor',
    });
    expect(config.squezelinkApi?.output.override.operations).toBeUndefined();
  });

  it('with infinite operations named, sets the infinite query on those operations only', () => {
    const infinite = { cursorParam: 'cursor', operations: ['ListMyLinks'] };
    const options = { ...PATHS, apis: [{ ...LINKS_API, infinite }] };

    const config = defineOrvalConfig(options);

    expect(config.squezelinkApi?.output.override.query).toBeUndefined();
    expect(config.squezelinkApi?.output.override.operations).toEqual({
      ListMyLinks: { query: { useInfinite: true, useInfiniteQueryParam: 'cursor' } },
    });
  });

  it('with apis omitted, builds the default six apis with no infinite query', () => {
    const options = { ...PATHS };

    const config = defineOrvalConfig(options);

    expect(Object.keys(config)).toHaveLength(6);
    expect(config.onlineMenuApi?.output.override.query).toBeUndefined();
  });
});
